/*
 * The built-in and template vocabulary, keyed by its English text (see src/lib/people/words.ts): kinds, relations,
 * attributes and the "Your child" / "Emma's teacher" phrases. Generated here so English never drifts from the model;
 * Danish (da/people.ts) translates the same keys.
 */
const templates = Object.values(TEMPLATES);
const allKinds = [...BUILTIN_KINDS, ...templates.flatMap((t) => t.kinds)];
const allRelations = [...BUILTIN_RELATIONS, ...templates.flatMap((t) => t.relations)];
const allAttributes = [...BUILTIN_ATTRIBUTES, ...templates.flatMap((t) => t.attributes)];
const ok = (s: string) => !!s && !s.includes(".");
const table = (pairs: [string, string][]): MessageTree => Object.fromEntries(pairs.filter(([k]) => ok(k)));
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

const relLabels = [...new Set(allRelations.flatMap((r) => [r.label, r.inverseLabel]))];
const nouns = [...new Set([
  ...relLabels.filter((l) => l.endsWith(" of")).map((l) => l.slice(0, -3).toLowerCase()),
  ...allKinds.filter((k) => k.nodeType === "person" && k.key !== "other").map((k) => k.label.toLowerCase()),
])];
const verbs = relLabels.filter((l) => !l.endsWith(" of")).map((l) => l.toLowerCase());

const circles: MessageTree = Object.fromEntries(templates.map((t) => [t.kind, table(t.circles.map((c) => [c.key, c.label]))]));
