// Make the Documentation section's data from the film, so the guides and the film never disagree:
//
//   node ops/video/my-graph/guides.mjs           # after voice.py and render.mjs (needs build/plan.json and build/timing.json)
//   node ops/video/my-graph/guides.mjs --local   # also copy the media into the local DOCS_MEDIA_DIR (default ./data/uploads/docs)
//
// Writes
//   src/lib/docs/film.ts              the film's files, chapters (with start times), transcript, guides and the allow-list
//   src/lib/docs/guides-en.ts, -da.ts the guides' words as message trees (t("docs.guides.<chapter>.…")), English from the
//                                     narration, Danish from da.json
//   build/docs/                       every file the media route serves: the film, poster, captions, chapters and the
//                                     guides' screenshots as 1440-wide JPEGs (shot-<name>.jpg, ios-<name>.jpg)
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "../../..");
const BUILD = path.join(HERE, "build");
const DOCS = path.join(BUILD, "docs");
const FFMPEG = process.env.FFMPEG ?? "/opt/homebrew/bin/ffmpeg";
const script = JSON.parse(fs.readFileSync(path.join(HERE, "script.json"), "utf8"));
const da = JSON.parse(fs.readFileSync(path.join(HERE, "da.json"), "utf8"));
const plan = JSON.parse(fs.readFileSync(path.join(BUILD, "plan.json"), "utf8"));
const timing = JSON.parse(fs.readFileSync(path.join(BUILD, "timing.json"), "utf8"));
const OUT = script.out;
fs.mkdirSync(DOCS, { recursive: true });

const plain = (s) => s.replace(/\s*\|\s*/g, " ").replace(/\s+/g, " ").trim();
const segs = plan.segments;
const total = Object.values(timing).reduce((m, t) => Math.max(m, t.start + t.duration), 0);
const chapters = segs.filter((s) => s.scene === "chapter").map((s) => s.chapter);

// Guides: one per chapter, its segments in order (the chapter card itself gives the title and the one-line summary).
const guides = chapters.map((id) => {
  const card = segs.find((s) => s.scene === "chapter" && s.chapter === id);
  const parts = segs.filter((s) => s.chapter === id && s.scene !== "chapter");
  return {
    id,
    start: +timing[card.id].start.toFixed(2),
    parts: parts.map((s) => ({
      id: s.id,
      start: +(timing[s.id].start + timing[s.id].lead).toFixed(2),
      shot: s.scene === "screen" ? `shot-${s.shot}.jpg` : s.scene === "phones" ? `ios-${path.basename(s.phones[0].src, ".jpg")}.jpg` : null,
      shots: s.scene === "phones" ? s.phones.map((p) => `ios-${path.basename(p.src, ".jpg")}.jpg`) : s.scene === "screen" ? [`shot-${s.shot}.jpg`] : [],
    })),
  };
});

// Messages, per language.
function tree(lang) {
  const out = {};
  for (const g of guides) {
    const card = segs.find((s) => s.scene === "chapter" && s.chapter === g.id);
    const d = da[card.id] ?? {};
    out[g.id] = { title: lang === "da" ? d.title : card.title, sub: lang === "da" ? d.sub : card.sub, parts: {} };
    for (const p of g.parts) {
      const s = segs.find((x) => x.id === p.id);
      const dd = da[p.id] ?? {};
      const title = s.title ?? (s.lines ? s.lines.map((l) => l.replace(/^\*/, "")).join(" ") : "");
      out[g.id].parts[p.id.replace(/[^a-z0-9]/gi, "_")] = lang === "da" ? { title: dd.title, text: dd.text } : { title, text: plain(s.say) };
    }
  }
  for (const [k, v] of Object.entries(out)) {
    if (!v.title || !v.sub) throw new Error(`${lang}: chapter ${k} has no title or summary`);
    for (const [pk, pv] of Object.entries(v.parts)) if (!pv.title || !pv.text) throw new Error(`${lang}: ${k}.${pk} has no title or text`);
  }
  return out;
}
const ts = (o) => JSON.stringify(o, null, 2);
const header = (what) => `/* Generated by ops/video/my-graph/guides.mjs from the film's script. Don't edit by hand: change script.json or da.json and run it again. */\n`;
for (const lang of ["en", "da"]) {
  fs.writeFileSync(path.join(ROOT, `src/lib/docs/guides-${lang}.ts`), `${header()}import type { MessageTree } from "@/lib/i18n/core";\n\n/** The written guides (${lang === "en" ? "English, the film's narration" : "Danish"}), one per chapter: t("docs.guides.<chapter>.title"). */\nconst guides: MessageTree = ${ts(tree(lang))};\n\nexport default guides;\n`);
}

// Screens for the guides: 1440-wide JPEGs.
const shotFiles = new Set();
for (const g of guides) for (const p of g.parts) for (const f of p.shots) shotFiles.add(f);
for (const f of shotFiles) {
  const src = f.startsWith("shot-") ? path.join(BUILD, "shots", f.slice(5).replace(/\.jpg$/, ".png")) : path.join(HERE, "ios", f.slice(4));
  const dst = path.join(DOCS, f);
  if (!fs.existsSync(src)) { console.warn(`missing ${src}: run shots.mjs`); continue; }
  const r = spawnSync(FFMPEG, ["-v", "error", "-y", "-i", src, "-vf", f.startsWith("shot-") ? "scale=1440:-2" : "scale=600:-2", "-q:v", "4", dst], { stdio: "inherit" });
  if (r.status) throw new Error("ffmpeg " + f);
}

// Transcript: one paragraph per scene that speaks, with the second the voice starts.
const transcript = segs.map((s) => ({ t: +(timing[s.id].start + timing[s.id].lead).toFixed(2), chapter: s.chapter ?? null, text: plain(s.say) }));

const FILM_FILES = [`${OUT}.mp4`, `${OUT}-poster.png`, `${OUT}.vtt`, `${OUT}.srt`, `${OUT}-chapters.json`];
for (const f of FILM_FILES) if (fs.existsSync(path.join(BUILD, f))) fs.copyFileSync(path.join(BUILD, f), path.join(DOCS, f));

fs.writeFileSync(path.join(ROOT, "src/lib/docs/film.ts"), `${header()}
/** "My Graph, explained": the film's files (served by /api/docs/media/[file]), its chapters and transcript. */
export const FILM = {
  title: ${JSON.stringify(script.title)},
  video: ${JSON.stringify(FILM_FILES[0])},
  poster: ${JSON.stringify(FILM_FILES[1])},
  vtt: ${JSON.stringify(FILM_FILES[2])},
  srt: ${JSON.stringify(FILM_FILES[3])},
  chapters: ${JSON.stringify(FILM_FILES[4])},
  /** Seconds. */
  duration: ${total.toFixed(2)},
} as const;

/** The film's files, in the order publish.mjs uploads them. */
export const FILM_FILES: readonly string[] = ${JSON.stringify(FILM_FILES)};

/** The guides' screenshots. */
export const SHOT_FILES: readonly string[] = ${JSON.stringify([...shotFiles].sort(), null, 2)};

export type GuidePart = { id: string; key: string; start: number; shots: readonly string[] };
export type Guide = { id: string; start: number; parts: readonly GuidePart[] };

/** One guide per chapter, in the film's order. Words: t("docs.guides.<id>.title" | ".sub" | ".parts.<key>.title" | ".text"). */
export const GUIDES: readonly Guide[] = ${ts(guides.map((g) => ({ id: g.id, start: g.start, parts: g.parts.map((p) => ({ id: p.id, key: p.id.replace(/[^a-z0-9]/gi, "_"), start: p.start, shots: p.shots })) })))};

/** What is said, scene by scene, and the second it starts (English: the film is in English). */
export const TRANSCRIPT: readonly { t: number; chapter: string | null; text: string }[] = ${ts(transcript)};
`);

// Anything in build/docs that isn't on the list is left from an earlier run: remove it (publish only sends this folder).
const keep = new Set([...FILM_FILES, ...shotFiles]);
for (const f of fs.readdirSync(DOCS)) if (!keep.has(f)) { fs.rmSync(path.join(DOCS, f)); console.log("removed stale", f); }

console.log(`guides ${guides.length}, shots ${shotFiles.size}, film ${(total / 60).toFixed(2)} min -> ${path.relative(ROOT, DOCS)}`);

if (process.argv.includes("--local")) {
  const dir = process.env.DOCS_MEDIA_DIR ? path.resolve(process.env.DOCS_MEDIA_DIR) : path.join(path.resolve(ROOT, process.env.UPLOAD_DIR || "data/uploads"), "docs");
  fs.mkdirSync(dir, { recursive: true });
  let n = 0;
  for (const f of fs.readdirSync(DOCS)) { fs.copyFileSync(path.join(DOCS, f), path.join(dir, f)); n++; }
  console.log(`copied ${n} files to ${dir}`);
}
